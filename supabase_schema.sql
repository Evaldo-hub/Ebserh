-- Schema para o Supabase - EBSERH Study App
-- Execute este SQL no painel SQL do seu projeto Supabase

-- Tabela de Questões
CREATE TABLE IF NOT EXISTS questoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_local INTEGER UNIQUE,  -- ID do SQLite local
    disciplina TEXT NOT NULL,
    semana INTEGER NOT NULL,
    nivel TEXT NOT NULL CHECK (nivel IN ('Básico', 'Alto', 'Pegadinha')),
    banca TEXT NOT NULL,
    enunciado TEXT NOT NULL,
    alternativas TEXT NOT NULL,  -- JSON com as alternativas
    resposta_correta TEXT NOT NULL,
    comentario TEXT NOT NULL,
    data_sincronizacao TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Tabela de Desempenho
CREATE TABLE IF NOT EXISTS desempenho (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_local INTEGER UNIQUE,  -- ID do SQLite local
    questao_id_local INTEGER NOT NULL,  -- ID da questão no SQLite local
    resposta_usuario TEXT NOT NULL,
    acerto BOOLEAN NOT NULL,
    data_resposta TIMESTAMP WITH TIME ZONE,
    data_sincronizacao TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Índices para melhor performance
CREATE INDEX IF NOT EXISTS idx_questoes_id_local ON questoes(id_local);
CREATE INDEX IF NOT EXISTS idx_questoes_disciplina ON questoes(disciplina);
CREATE INDEX IF NOT EXISTS idx_questoes_semana ON questoes(semana);
CREATE INDEX IF NOT EXISTS idx_questoes_nivel ON questoes(nivel);

CREATE INDEX IF NOT EXISTS idx_desempenho_id_local ON desempenho(id_local);
CREATE INDEX IF NOT EXISTS idx_desempenho_questao_id_local ON desempenho(questao_id_local);
CREATE INDEX IF NOT EXISTS idx_desempenho_acerto ON desempenho(acerto);
CREATE INDEX IF NOT EXISTS idx_desempenho_data_resposta ON desempenho(data_resposta);

