-- Função para atualizar updated_at automaticamente
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ language 'plpgsql';

-- Triggers para atualizar updated_at
CREATE TRIGGER update_questoes_updated_at 
    BEFORE UPDATE ON questoes 
    FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER update_desempenho_updated_at 
    BEFORE UPDATE ON desempenho 
    FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- Comentários sobre as tabelas
COMMENT ON TABLE questoes IS 'Tabela de questões de estudo sincronizadas do SQLite local';
COMMENT ON TABLE desempenho IS 'Tabela de desempenho dos usuários sincronizada do SQLite local';

-- Comentários sobre colunas importantes
COMMENT ON COLUMN questoes.id_local IS 'ID original da tabela SQLite local';
COMMENT ON COLUMN questoes.alternativas IS 'JSON com as alternativas da questão';
COMMENT ON COLUMN desempenho.id_local IS 'ID original da tabela SQLite local';
COMMENT ON COLUMN desempenho.questao_id_local IS 'ID da questão na tabela SQLite local';
